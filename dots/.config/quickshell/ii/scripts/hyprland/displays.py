#!/usr/bin/env python3
"""Preview a display layout; only persist it after an explicit Keep response."""
import json
import math
import os
from pathlib import Path
import re
import select
import signal
import subprocess
import sys
import tempfile
import time


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text)
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def validate(layout):
    if not isinstance(layout, list) or not layout or len(layout) > 16:
        raise ValueError("Choose at least one display")
    names = set()
    for item in layout:
        name = item["name"]
        if not re.fullmatch(r"[\w.-]+", name) or name in names:
            raise ValueError("Invalid or duplicate display name")
        names.add(name)
        if not re.fullmatch(r"\d+x\d+@[\d.]+(?:Hz)?", item["mode"]):
            raise ValueError("Choose a valid display mode")
        scale = float(item["scale"])
        if not math.isfinite(scale) or not 0.5 <= scale <= 4:
            raise ValueError("Scale must be between 50% and 400%")
        for key in ("x", "y"):
            if type(item[key]) is not int or abs(item[key]) > 32768:
                raise ValueError("Invalid display position")
        if type(item["transform"]) is not int or item["transform"] not in range(8):
            raise ValueError("Invalid display rotation")
    return layout


def current_layout():
    monitors = json.loads(subprocess.check_output(["hyprctl", "monitors", "all", "-j"], timeout=5))
    return [dict(name=m["name"], mode=f'{m["width"]}x{m["height"]}@{m["refreshRate"]}',
                 x=m["x"], y=m["y"], scale=m["scale"], transform=m.get("transform", 0),
                 modes=m.get("availableModes", []), disabled=m.get("disabled", False)) for m in monitors]


def monitor_rule(item):
    output = json.dumps(item["name"], ensure_ascii=False)
    if item.get("disabled"):
        return f"hl.monitor({{ output = {output}, disabled = true }})"
    return ('hl.monitor({ output = %s, disabled = false, mode = %s, position = %s, scale = %s, transform = %s })' % (
        output, json.dumps(item["mode"]), json.dumps(f'{item["x"]}x{item["y"]}'), item["scale"], item["transform"]))


def layout_matches(expected, actual):
    by_name = {item["name"]: item for item in actual}
    for item in expected:
        current = by_name.get(item["name"])
        if item.get("disabled"):
            if current and not current.get("disabled"):
                return False
            continue
        if not current or current.get("disabled"):
            return False
        size, rate = item["mode"].removesuffix("Hz").split("@")
        actual_size, actual_rate = current["mode"].removesuffix("Hz").split("@")
        if size != actual_size or abs(float(rate) - float(actual_rate)) > 0.15:
            return False
        if any(item[key] != current[key] for key in ("x", "y", "scale", "transform")):
            return False
    return True


def apply(layout):
    for item in layout:
        result = subprocess.run(["hyprctl", "eval", monitor_rule(item)], capture_output=True, text=True, timeout=5)
        if result.returncode or result.stdout.strip() != "ok":
            raise RuntimeError(result.stderr.strip() or result.stdout.strip() or "Could not apply display layout")
    deadline = time.monotonic() + 3
    while not layout_matches(layout, current_layout()):
        if time.monotonic() >= deadline:
            raise RuntimeError("The display did not accept the requested mode or rotation; the previous layout will be restored")
        time.sleep(0.1)


def persist(layout):
    config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "hypr"
    path = config / "custom/shell-monitors.lua"
    lines = ["-- Generated by shell display settings.\n"]
    for item in layout:
        lines.append(monitor_rule(item) + "\n")
    atomic_write(path, "".join(lines))


def preview(layout):
    validate(layout)
    previous = current_layout()
    connected = {m["name"] for m in previous if not m["disabled"]}
    if {m["name"] for m in layout} != connected:
        raise ValueError("Displays changed; refresh the layout and try again")
    kept = False
    signal.signal(signal.SIGTERM, lambda *_: sys.exit(1))
    try:
        apply(layout)
        print(json.dumps({"preview": True}), flush=True)
        ready, _, _ = select.select([sys.stdin], [], [], 15)
        if ready and sys.stdin.readline().strip() == "keep":
            persist(layout)
            kept = True
    finally:
        if not kept:
            apply(previous)
    print(json.dumps({"kept": kept}), flush=True)


if __name__ == "__main__":
    try:
        if sys.argv[1] == "list":
            print(json.dumps(current_layout()))
        elif sys.argv[1] == "preview":
            preview(json.loads(sys.stdin.readline()))
        else:
            raise ValueError("Unknown display action")
    except (ValueError, KeyError, OSError, RuntimeError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
